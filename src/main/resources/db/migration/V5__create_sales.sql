CREATE SEQUENCE sale_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_number VARCHAR(20) NOT NULL,
    user_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sales_sale_number UNIQUE (sale_number),
    CONSTRAINT fk_sales_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_sales_number_not_blank CHECK (BTRIM(sale_number) <> ''),
    CONSTRAINT ck_sales_status CHECK (status IN ('COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_sales_total_positive CHECK (total > 0),
    CONSTRAINT ck_sales_updated_at CHECK (updated_at >= created_at)
);

CREATE INDEX idx_sales_user_created_at ON sales (user_id, created_at DESC);
CREATE INDEX idx_sales_status_created_at ON sales (status, created_at DESC);
CREATE INDEX idx_sales_created_at ON sales (created_at DESC);

CREATE TABLE sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name VARCHAR(160) NOT NULL,
    quantity NUMERIC(12, 3) NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_sale_items_sale FOREIGN KEY (sale_id) REFERENCES sales (id),
    CONSTRAINT fk_sale_items_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT uq_sale_items_sale_product UNIQUE (sale_id, product_id),
    CONSTRAINT ck_sale_items_product_name_not_blank CHECK (BTRIM(product_name) <> ''),
    CONSTRAINT ck_sale_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_sale_items_unit_price_positive CHECK (unit_price > 0),
    CONSTRAINT ck_sale_items_subtotal_positive CHECK (subtotal > 0)
);

CREATE INDEX idx_sale_items_sale_id ON sale_items (sale_id);
CREATE INDEX idx_sale_items_product_id ON sale_items (product_id);

CREATE TABLE sale_idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    sale_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_sale_idempotency_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_sale_idempotency_sale FOREIGN KEY (sale_id) REFERENCES sales (id),
    CONSTRAINT uq_sale_idempotency_user_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT uq_sale_idempotency_sale UNIQUE (sale_id),
    CONSTRAINT ck_sale_idempotency_key_not_blank CHECK (BTRIM(idempotency_key) <> ''),
    CONSTRAINT ck_sale_idempotency_hash_format CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sale_idempotency_status CHECK (status IN ('PROCESSING', 'COMPLETED')),
    CONSTRAINT ck_sale_idempotency_completion CHECK (
        (status = 'PROCESSING' AND sale_id IS NULL)
        OR (status = 'COMPLETED' AND sale_id IS NOT NULL)
    ),
    CONSTRAINT ck_sale_idempotency_updated_at CHECK (updated_at >= created_at)
);

CREATE INDEX idx_sale_idempotency_created_at ON sale_idempotency_keys (created_at);
