CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_categories_name_not_blank CHECK (BTRIM(name) <> '')
);

CREATE UNIQUE INDEX uq_categories_normalized_name
    ON categories (LOWER(BTRIM(name)));

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    description VARCHAR(500),
    barcode VARCHAR(64),
    price NUMERIC(12, 2) NOT NULL,
    category_id BIGINT NOT NULL,
    unit_of_measure VARCHAR(10) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_products_name_not_blank CHECK (BTRIM(name) <> ''),
    CONSTRAINT ck_products_barcode_not_blank CHECK (barcode IS NULL OR BTRIM(barcode) <> ''),
    CONSTRAINT ck_products_price_positive CHECK (price > 0),
    CONSTRAINT ck_products_unit_of_measure
        CHECK (unit_of_measure IN ('UND', 'KG', 'GR', 'LT', 'ML', 'PACK'))
);

CREATE UNIQUE INDEX uq_products_barcode
    ON products (barcode)
    WHERE barcode IS NOT NULL;

CREATE INDEX idx_products_normalized_name
    ON products (LOWER(name));

CREATE INDEX idx_products_active_name
    ON products (active, LOWER(name));

CREATE INDEX idx_products_category_id
    ON products (category_id);
